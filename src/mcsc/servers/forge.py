"""Forge server."""

from __future__ import annotations

import logging
import os
import subprocess
from pathlib import Path

from mcsc.config import ServerType
from mcsc.download import download_file
from mcsc.exceptions import InstallError, UnsupportedVersionError
from mcsc.servers.base import MinecraftServer
from mcsc.versions import version_key

logger = logging.getLogger(__name__)


class ForgeServer(MinecraftServer):
    """Minecraft Forge server (1.17+).

    Layout: the installer lives in :attr:`path`, the installed server in
    ``path / "server"``. The server is launched with Java directly, using the
    argument files generated by the installer (the same thing ``run.bat`` /
    ``run.sh`` do), so it works on every OS and RAM settings are always applied.
    """

    server_type = ServerType.FORGE
    INSTALLER_NAME = "forge-installer.jar"
    INSTALL_DIR = "server"

    @property
    def server_dir(self) -> Path:
        return self.path / self.INSTALL_DIR

    @property
    def installer_path(self) -> Path:
        return self.path / self.INSTALLER_NAME

    @property
    def mods_dir(self) -> Path:
        return self.server_dir / "mods"

    def install(self, download_url: str, *, accept_eula: bool = False) -> None:
        """Download the Forge installer and run it. Blocking (can take minutes)."""
        logger.info("Installing %r into %s", self, self.path)
        self.path.mkdir(parents=True, exist_ok=True)
        download_file(download_url, self.installer_path)

        command = [
            self.config.java_path,
            "-jar",
            self.INSTALLER_NAME,
            "--installServer",
            self.INSTALL_DIR,
        ]
        try:
            result = subprocess.run(
                command,
                cwd=self.path,
                capture_output=True,
                text=True,
                errors="replace",
                check=False,
            )
        except FileNotFoundError as e:
            raise InstallError(f"Java executable not found: {self.config.java_path!r}") from e
        if result.returncode != 0:
            raise InstallError(
                f"Forge installer exited with code {result.returncode}:\n"
                + (result.stdout or "")[-2000:]
            )
        self._args_file()  # fail now if the installed layout is not supported
        if accept_eula:
            self.accept_eula()

    def _args_file(self) -> Path:
        """Argument file generated by the Forge installer (relative to :attr:`server_dir`)."""
        name = "win_args.txt" if os.name == "nt" else "unix_args.txt"
        base = self.server_dir / "libraries" / "net" / "minecraftforge" / "forge"
        candidates = sorted(
            base.glob(f"*/{name}"),
            key=lambda p: version_key(p.parent.name),
            reverse=True,
        )
        if not candidates:
            raise UnsupportedVersionError(
                f"Forge {self.version} has no {name}; only Forge for Minecraft 1.17+ is supported"
            )
        for candidate in candidates:
            if candidate.parent.name == self.version:
                return candidate.relative_to(self.server_dir)
        return candidates[0].relative_to(self.server_dir)

    def build_command(self) -> list[str]:
        ram = self.config.ram_gb
        command = [self.config.java_path]
        if (self.server_dir / "user_jvm_args.txt").is_file():
            command.append("@user_jvm_args.txt")
        # After user_jvm_args.txt, so the configured RAM wins.
        command += [f"-Xmx{ram}G", f"-Xms{ram}G", *self.config.jvm_args]
        command += [f"@{self._args_file().as_posix()}", "nogui"]
        return command
